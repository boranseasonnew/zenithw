import {build} from 'esbuild';
import {readFileSync} from 'node:fs';
import {writeFileWithRetry} from '../shared/build-files.mjs';

const output='frontend/app.d4596317c4a7.js';
const result=await build({
 entryPoints:['shared/web-app/index.mjs'],bundle:true,write:false,
 format:'iife',platform:'browser',target:'es2022',external:['/download-safety.js'],
	legalComments:'eof',charset:'utf8',minify:true,
 banner:{js:'// Generated by scripts/build-web-app.mjs; edit shared/web-app/ instead.'},
});
const code=result.outputFiles[0].text;
if(process.argv.includes('--check')){
 if(readFileSync(output,'utf8').replaceAll('\r\n','\n')!==code)throw Error('Web app bundle is stale; run node scripts/build-web-app.mjs');
 console.log('Web app bundle matches its ES module sources.');
}else{
 writeFileWithRetry(output,code,'utf8');
 console.log('Built modular web app into the existing classic-script entry point.');
}
